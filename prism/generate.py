"""Render a QueryProfile into the four files a parity case needs.

Split from ``analyse.py`` on purpose. Analysis is where the risk lives -- a
mis-parsed SELECT list makes every output wrong -- so it is separately testable
against a query whose correct answers are already known. This module is
templating, and templating that reads a dataclass is hard to get subtly wrong.

Every generated file carries a header saying it was generated, from what, and
that it is meant to be edited. PRISM is a first draft, not an owner: it cannot
know that a dimension is really a metric in disguise, or that your team spells a
label differently. A generator that pretends otherwise produces files nobody
dares touch.
"""

from __future__ import annotations

import datetime
import os
from typing import Dict, List

from .analyse import QueryProfile

# Where the four files land, relative to the repo root. These mirror the layout
# the existing case uses; PRISM does not invent a new one.
SQL_DIR = os.path.join("sql", "insight_plus")
CASE_DIR = os.path.join("scripts", "cases_insight_plus")
TEST_DIR = "tests"

# Defaults for the two sides. Overridable, because a second migration will have
# different catalogs -- but defaulted, because for this project they do not.
DEFAULT_EXPECTED_FACTS = "mrm_log_flat.default"
DEFAULT_ACTUAL_FACTS = "etl.public_test1"
DEFAULT_EXPECTED_LABEL = "Hoover"
DEFAULT_ACTUAL_LABEL = "Hoover++"


def _banner(profile: QueryProfile, kind: str) -> str:
    stamp = datetime.date.today().isoformat()
    return (
        f"Generated by PRISM from {profile.sql_path} on {stamp}.\n"
        f"\n"
        f"PRISM derives what the query already states: the keys are its GROUP BY\n"
        f"dimensions, the breakdown column is the one dimension that is a distinct\n"
        f"literal per UNION branch, the unordered arrays are the ones that reach the\n"
        f"output from a source column rather than being constructed inline.\n"
        f"\n"
        f"EDIT THIS FILE. It is a first draft, not a contract. Re-running PRISM\n"
        f"overwrites it, so once you have changed something, stop re-generating and\n"
        f"own it -- or pass --only to regenerate the files you have not touched.\n"
        f"\n"
        f"Source query: {profile.output_columns} output columns "
        f"({len(profile.dimensions)} dimensions + {len(profile.metrics)} metrics), "
        f"{profile.branches} UNION branch(es)."
    )


def _comment(text: str, prefix: str) -> str:
    return "\n".join(f"{prefix} {line}".rstrip() for line in text.splitlines())


