def render_case_yaml(
    profile: QueryProfile,
    *,
    expected_facts: str = DEFAULT_EXPECTED_FACTS,
    actual_facts: str = DEFAULT_ACTUAL_FACTS,
    expected_label: str = DEFAULT_EXPECTED_LABEL,
    actual_label: str = DEFAULT_ACTUAL_LABEL,
    sampling_filter: str = (
        "bitwise_and(coalesce(request__bit_flags, BIGINT '0'),"
        "bitwise_left_shift(BIGINT '1', 59)) > 0"
    ),
    with_drilldown: bool = True,
) -> str:
    p = profile
    L: List[str] = [_comment(_banner(p, "case"), "#"), ""]
    L += [
        "cases:",
        f"  - name: {p.name}",
        f"    expected_label: {expected_label}",
        f"    actual_label: {actual_label}",
        "    description: >-",
        f"      The {p.name} aggregate must produce identical rows whether built",
        f"      from the {expected_label} layout or the {actual_label} layout. Both",
        "      sides are queries; neither is materialised.",
        "",
    ]

    if "sampling_filter" in p.placeholders:
        L += [
            "    # Shared by BOTH sides, and case-level on purpose: it is the one thing",
            "    # that must never differ. Comparing a sampled side against an unsampled",
            "    # one measures the sampling ratio and nothing else. Defined once and",
            "    # used by both, that bug is not expressible.",
            "    vars:",
            f'      sampling_filter: "{sampling_filter}"',
            "",
        ]

    rel = os.path.relpath(
        os.path.join(SQL_DIR, os.path.basename(p.sql_path)), CASE_DIR
    ).replace(os.sep, "/")
    L += [
        "    # The only difference between the two runs. These outrank --param",
        "    # deliberately: a --param reaching both sides would point them at the",
        "    # same catalog, and a comparison of a table with itself always passes.",
        "    expected:",
        "      type: trino",
        f"      query_file: {rel}",
        "      vars:",
        f"        facts: {expected_facts}",
        "",
        "    actual:",
        "      type: trino",
        f"      query_file: {rel}",
        "      vars:",
        f"        facts: {actual_facts}",
        "",
        "    compare:",
        f"      # The {len(p.dimensions)} GROUP BY dimensions. Not a business key, but unique by",
        "      # construction after the outer aggregation, which is all a key has to be.",
        "      # Keyed, a difference separates into missing/added (a dimension combination",
        "      # is absent) and changed (same dimensions, drifting metrics). Keyless, every",
        "      # difference is missing + added and every column reads as differing.",
        "      keys:",
    ]
    L += [f"        - {d}" for d in p.dimensions]

    if p.unordered_arrays:
        L += [
            "",
            "      # Arrays that reach the output from a source column, whose element",
            "      # order the engine does not guarantee. rowparity treats list as",
            "      # ORDERED by default, so without this a pure ordering difference",
            "      # reads as a data difference.",
        ]
        if p.constructed_arrays:
            L.append(
                "      # Not listed: "
                + ", ".join(p.constructed_arrays)
                + " -- constructed inline, so they cannot vary."
            )
        L.append("      unordered_list_columns:")
        L += [f"        - {c}" for c in p.unordered_arrays]

    L += ["", "      max_examples: 50"]

    if p.breakdown_by:
        L += [
            "",
            "      # Split every difference by which UNION branch produced it. This",
            f"      # column is a hardcoded literal per branch ({', '.join(repr(v) for v in p.breakdown_values)}),",
            "      # so it partitions the output exactly -- and because it is also a key,",
            "      # its value is available for missing, added and changed rows alike.",
            f"      breakdown_by: {p.breakdown_by}",
        ]

    L += [
        "",
        "      # Find the single key column whose drift turned one logical row into a",
        "      # missing + added pair. Costs no warehouse time: it re-pairs key tuples",
        "      # already in memory.",
        "      near_miss: true",
    ]

    if p.row_summary:
        L += [
            "",
            "    # How a differing row is digested in the report, instead of dumping a",
            f"    # {p.output_columns}-column dict truncated after the first four.",
            "    # DERIVED FROM COLUMN NAMES, not from the query -- review these.",
            "    row_summary:",
        ]
        for g in p.row_summary:
            cols = ", ".join(g["columns"])
            L.append(f'      - {{label: "{g["label"]}", columns: [{cols}]}}')

    if with_drilldown and p.batch_param:
        dd = os.path.relpath(
            os.path.join(SQL_DIR, f"{p.name}_drilldown.sql"), CASE_DIR
        ).replace(os.sep, "/")
        L += [
            "",
            "    # Per-row investigation SQL, generated but NOT executed -- running both",
            "    # sides was tried and taken back out: the two scans dominated the parity",
            "    # run they were meant to annotate.",
            "    drilldown:",
            f"      query_file: {dd}",
            "      # An output alias mapped to its SOURCE expression: the alias is not",
            "      # what a predicate against the raw table can filter on. Exactly one",
            "      # column, because the generated predicate is an IN-list over its values.",
            "      bind:",
            "        creative_id: \"if(network_is_ad_owner, coalesce(advertisement__creative_id, -1), -1)\"",
            "      id_column: request__transaction_id",
            "      # Missing rows only: 'this did not arrive, where did its transactions",
            "      # go?' is the question a drill-down is opened to answer.",
            "      kinds: [missing]",
            "      # DERIVED from the run's batch parameter, never typed in. A hardcoded",
            "      # date goes stale the moment you drill a different batch, and nothing",
            "      # in the output says the window was wrong.",
            "      time:",
            f"        param: {p.batch_param}",
            '        format: "%Y%m%d%H%M%S"',
            "        hours_before: 1",
            "        hours_after: 3",
            "      # Deliberately ASYMMETRIC: the migrated side is pinned to the batch",
            "      # hour, the source side searched wider, because 'the event_date",
            "      # shifted' is the hypothesis under test. Pinning both assumes the answer.",
            "      vars:",
            "        expected:",
            "          time_filter: >-",
            "            date_trunc('HOUR', cast(ack__timestamp as timestamp)) >= timestamp '${batch_hour_start}'",
            "            and date_trunc('HOUR', cast(ack__timestamp as timestamp)) < timestamp '${batch_hour_end}'",
            "        actual:",
            "          time_filter: >-",
            "            date_trunc('HOUR', cast(ack__timestamp as timestamp)) = timestamp '${batch_hour}'",
        ]

    L += ["", "    tags: [insight_plus, prism]", ""]
    return "\n".join(L)


